// Deterministic void-and-cluster threshold mask, generated once rather than
// allocating random noise while playing an animation.
// Method: https://momentsingraphics.de/BlueNoise.html
import {writeFileSync} from 'node:fs';
const side=64,count=side*side,sigma=1.9,radius=6;
const occupied=new Uint8Array(count),energy=new Float64Array(count),ranks=new Uint16Array(count);
const kernel=[];
for(let y=-radius;y<=radius;y++)for(let x=-radius;x<=radius;x++)kernel.push([x,y,Math.exp(-(x*x+y*y)/(2*sigma*sigma))]);
function set(index,on) {
  const delta=on-occupied[index];occupied[index]=on;
  const x=index%side,y=Math.floor(index/side);
  for(const [dx,dy,weight] of kernel)energy[((y+dy+side)%side)*side+(x+dx+side)%side]+=delta*weight;
}
function extreme(on,max) {
  let result=-1,best=max?-Infinity:Infinity;
  for(let i=0;i<count;i++)if(occupied[i]===on&&(max?energy[i]>best:energy[i]<best)){best=energy[i];result=i;}
  return result;
}
let seed=0x746f7370;
function random(){seed^=seed<<13;seed^=seed>>>17;seed^=seed<<5;return seed>>>0;}
const initial=Math.floor(count*0.1);
for(let placed=0;placed<initial;){const i=random()%count;if(!occupied[i]){set(i,1);placed++;}}
let settled=false;
for(let iteration=0;iteration<count*10;iteration++) {
  const cluster=extreme(1,true);set(cluster,0);
  const hole=extreme(0,false);set(hole,1);
  if(cluster===hole){settled=true;break;}
}
if(!settled)throw new Error('Noise mask did not converge.');
const prototype=occupied.slice();
for(let rank=initial-1;rank>=0;rank--){const i=extreme(1,true);set(i,0);ranks[i]=rank;}
for(let i=0;i<count;i++)if(prototype[i])set(i,1);
for(let rank=initial;rank<count/2;rank++){const i=extreme(0,false);set(i,1);ranks[i]=rank;}
// The upper half distributes holes in the same way as the lower half's dots.
const complement=Uint8Array.from(occupied,v=>1-v);occupied.fill(0);energy.fill(0);
for(let i=0;i<count;i++)if(complement[i])set(i,1);
for(let rank=count/2;rank<count;rank++){const i=extreme(1,true);set(i,0);ranks[i]=rank;}
const bytes=Uint8Array.from(ranks,rank=>Math.floor(rank/16));
const lines=Array.from({length:side},(_,row)=>'  '+[...bytes.subarray(row*side,(row+1)*side)].join(','));
writeFileSync(new URL('../sprite-noise.js',import.meta.url),'// Generated by tools/build-sprite-noise.mjs. Each threshold occurs 16 times.\nexport const SPRITE_NOISE_SIDE=64;\nexport const SPRITE_NOISE=new Uint8Array([\n'+lines.join(',\n')+'\n]);\n');
console.log('Built deterministic 64 by 64 blue-noise mask.');
